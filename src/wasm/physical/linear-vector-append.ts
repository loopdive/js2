import type { Instr, LocalDef, ValType } from "../model/instructions.js";
import {
  LINEAR_ARRAY_FORWARDING,
  LINEAR_VECTOR_ELEMENTS_OFFSET,
  LINEAR_VECTOR_MINIMUM_CAPACITY,
} from "../../shared/contracts/linear-memory-layout.js";

const MAXIMUM = Math.floor((0xffffffff - LINEAR_VECTOR_ELEMENTS_OFFSET) / 8);
const OLD = 3,
  LENGTH = 4,
  CAPACITY = 5,
  NEXT_CAPACITY = 6,
  NEXT = 7,
  NEXT_LENGTH = 8,
  BYTES = 9,
  OLD_END = 10;
const get = (index: number): Instr => ({ op: "local.get", index });
const set = (index: number): Instr => ({ op: "local.set", index });
const constant = (value: number): Instr => ({ op: "i32.const", value });
const trap = (): Instr => ({ op: "if", blockType: { kind: "empty" }, then: [{ op: "unreachable" }], else: [] });
const memoryBytes = (): Instr[] => [
  { op: "memory.size" },
  { op: "i64.extend_i32_u" },
  { op: "i64.const", value: 65536n },
  { op: "i64.mul" },
];
const end = (pointer: number, capacity: number): Instr[] => [
  get(pointer),
  { op: "i64.extend_i32_u" },
  get(capacity),
  { op: "i64.extend_i32_u" },
  { op: "i64.const", value: 8n },
  { op: "i64.mul" },
  { op: "i64.add" },
  { op: "i64.const", value: BigInt(LINEAR_VECTOR_ELEMENTS_OFFSET) },
  { op: "i64.add" },
];

/** Numeric append ABI differs from the value-first fixed-construction initializer. */
export function describeLinearNumericVectorAppend(): { params: ValType[]; results: ValType[]; locals: LocalDef[] } {
  return {
    params: [{ kind: "i32" }, { kind: "i32" }, { kind: "f64" }],
    results: [],
    locals: [
      ...["old", "length", "capacity", "next_capacity", "next", "next_length", "bytes"].map((name) => ({
        name,
        type: { kind: "i32" } as ValType,
      })),
      { name: "old_end", type: { kind: "i64" } },
    ],
  };
}

/** Caller must supply its issued, completed default allocator and forwarding resolver. */
export function buildLinearNumericVectorAppendBody(mallocFunctionIndex: number, resolveFunctionIndex: number): Instr[] {
  return [
    // Arguments have already evaluated. Resolve the current header once at entry.
    get(0),
    { op: "call", funcIdx: resolveFunctionIndex },
    set(OLD),
    get(OLD),
    { op: "i32.eqz" },
    trap(),
    get(OLD),
    constant(7),
    { op: "i32.and" },
    trap(),
    get(OLD),
    { op: "i64.extend_i32_u" },
    { op: "i64.const", value: 16n },
    { op: "i64.add" },
    ...memoryBytes(),
    { op: "i64.gt_u" },
    trap(),
    get(OLD),
    { op: "i32.load", align: 2, offset: 0 },
    constant(1),
    { op: "i32.ne" },
    trap(),
    get(OLD),
    { op: "i32.load", align: 2, offset: 8 },
    set(LENGTH),
    get(OLD),
    { op: "i32.load", align: 2, offset: 12 },
    set(CAPACITY),
    get(CAPACITY),
    constant(MAXIMUM),
    { op: "i32.gt_u" },
    trap(),
    ...end(OLD, CAPACITY),
    { op: "local.tee", index: OLD_END },
    ...memoryBytes(),
    { op: "i64.gt_u" },
    trap(),
    get(LENGTH),
    get(CAPACITY),
    { op: "i32.gt_u" },
    trap(),
    get(1),
    get(LENGTH),
    { op: "i32.ne" },
    trap(),
    get(LENGTH),
    constant(MAXIMUM),
    { op: "i32.ge_u" },
    trap(),
    get(LENGTH),
    constant(1),
    { op: "i32.add" },
    set(NEXT_LENGTH),
    get(LENGTH),
    get(CAPACITY),
    { op: "i32.eq" },
    {
      op: "if",
      blockType: { kind: "empty" },
      then: [
        get(CAPACITY),
        constant(Math.floor(MAXIMUM / 2)),
        { op: "i32.gt_u" },
        {
          op: "if",
          blockType: { kind: "empty" },
          then: [constant(MAXIMUM), set(NEXT_CAPACITY)],
          else: [get(CAPACITY), constant(2), { op: "i32.mul" }, set(NEXT_CAPACITY)],
        },
        get(NEXT_CAPACITY),
        get(NEXT_LENGTH),
        { op: "i32.lt_u" },
        { op: "if", blockType: { kind: "empty" }, then: [get(NEXT_LENGTH), set(NEXT_CAPACITY)], else: [] },
        get(NEXT_CAPACITY),
        constant(LINEAR_VECTOR_MINIMUM_CAPACITY),
        { op: "i32.lt_u" },
        {
          op: "if",
          blockType: { kind: "empty" },
          then: [constant(LINEAR_VECTOR_MINIMUM_CAPACITY), set(NEXT_CAPACITY)],
          else: [],
        },
        get(NEXT_CAPACITY),
        constant(8),
        { op: "i32.mul" },
        constant(16),
        { op: "i32.add" },
        { op: "local.tee", index: BYTES },
        { op: "call", funcIdx: mallocFunctionIndex },
        set(NEXT),
        // Allocation failure occurs before publication. Authenticate the whole returned range.
        get(NEXT),
        { op: "i32.eqz" },
        trap(),
        get(NEXT),
        constant(7),
        { op: "i32.and" },
        trap(),
        get(NEXT),
        { op: "i64.extend_i32_u" },
        get(OLD_END),
        { op: "i64.lt_u" },
        trap(),
        ...end(NEXT, NEXT_CAPACITY),
        ...memoryBytes(),
        { op: "i64.gt_u" },
        trap(),
        get(NEXT),
        constant(16),
        { op: "i32.add" },
        get(OLD),
        constant(16),
        { op: "i32.add" },
        get(CAPACITY),
        constant(8),
        { op: "i32.mul" },
        { op: "memory.copy" },
        get(NEXT),
        constant(1),
        { op: "i32.store", align: 2, offset: 0 },
        get(NEXT),
        constant(0),
        { op: "i32.store", align: 2, offset: 4 },
        get(NEXT),
        get(NEXT_CAPACITY),
        { op: "i32.store", align: 2, offset: 12 },
        get(NEXT),
        get(NEXT_LENGTH),
        { op: "i32.store", align: 2, offset: 8 },
        get(NEXT),
        get(LENGTH),
        constant(8),
        { op: "i32.mul" },
        { op: "i32.add" },
        get(2),
        { op: "f64.store", align: 3, offset: 16 },
        // One nontrapping final commit publishes tag at byte0 and pointer at byte4.
        get(OLD),
        get(NEXT),
        { op: "i64.extend_i32_u" },
        { op: "i64.const", value: 32n },
        { op: "i64.shl" },
        { op: "i64.const", value: BigInt(LINEAR_ARRAY_FORWARDING.tag) },
        { op: "i64.or" },
        { op: "i64.store", align: 3, offset: 0 },
      ],
      else: [
        get(OLD),
        get(LENGTH),
        constant(8),
        { op: "i32.mul" },
        { op: "i32.add" },
        get(2),
        { op: "f64.store", align: 3, offset: 16 },
        get(OLD),
        get(NEXT_LENGTH),
        { op: "i32.store", align: 2, offset: 8 },
      ],
    },
  ];
}
