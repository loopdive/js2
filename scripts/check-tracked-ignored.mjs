const allows = (entry, path) => (entry.path.endsWith("/") ? path.startsWith(entry.path) : path === entry.path);

function git(args, input) {
  const result = spawnSync("git", args, { cwd: ROOT, input, maxBuffer: 256 * 1024 * 1024 });
  if (result.error) throw result.error;
  return result;
}

/**
 * Parse `git check-ignore -z -v` output: records of
 * <source> NUL <linenum> NUL <pattern> NUL <pathname> NUL. With -v, a path
 * whose last matching rule is a `!` negation is listed too although it is NOT
 * ignored — those are dropped.
 * @returns {{path: string, rule: string}[]}
 */
export function parseCheckIgnoreVerbose(text) {
  const fields = text.split("\0");
  const out = [];
  for (let i = 0; i + 3 < fields.length; i += 4) {
    if (fields[i + 2].startsWith("!")) continue;
    out.push({ path: fields[i + 3], rule: `${fields[i]}:${fields[i + 1]}: ${fields[i + 2]}` });
  }
  return out;
}

/** @returns {{path: string, rule: string}[]} tracked paths that an ignore rule matches */
function trackedIgnored() {
  const listed = git(["ls-files", "-z"]);
  if (listed.status !== 0) throw new Error(`git ls-files failed: ${listed.stderr}`);
  // check-ignore exits 1 when NOTHING matches — that is the clean case.
  const checked = git(["check-ignore", "-z", "-v", "--stdin", "--no-index"], listed.stdout);
  if (checked.status !== 0 && checked.status !== 1) throw new Error(`git check-ignore failed: ${checked.stderr}`);
  return parseCheckIgnoreVerbose(checked.stdout.toString("utf8"));
}

export function evaluate(hits, allowed = ALLOWED) {
  const offenders = hits.filter((hit) => !allowed.some((entry) => allows(entry, hit.path)));
  const stale = allowed.filter((entry) => !hits.some((hit) => allows(entry, hit.path)));
  return { offenders, stale };
}

function main() {
  let hits;
  try {
    hits = trackedIgnored();
  } catch (error) {
    console.error(`check-tracked-ignored: FAILED — ${error.message}`);
    process.exit(2);
  }
  const { offenders, stale } = evaluate(hits);
  for (const hit of offenders) console.error(`  tracked but ignored: ${hit.path}  (${hit.rule})`);
  for (const entry of stale) console.error(`  stale allow-list entry (matches nothing): ${entry.path}`);
  if (offenders.length > 0) {
    console.error(
      "\nUntrack them (`git rm --cached <path>`), or — if they must stay tracked — add an ALLOWED entry " +
        "with a date and reason in scripts/check-tracked-ignored.mjs.",
    );
  }
  if (offenders.length > 0 || stale.length > 0) {
    console.error(`check-tracked-ignored: FAILED — ${offenders.length} offender(s), ${stale.length} stale entr(y/ies)`);
    process.exit(1);
  }
  console.log(
    `check-tracked-ignored: OK — ${hits.length} tracked-and-ignored path(s), all on the dated allow-list ` +
      `(${ALLOWED.length} entries)`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
