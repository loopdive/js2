// check:tracked-ignored (#6796) — no tracked file may match a .gitignore rule.
//
// A tracked-and-ignored file is invisible in two directions: `git add .` will
// never pick up a NEW sibling, and nobody notices the stale copy that is still
// in the index. That is how an 18 MB baseline JSONL, a retired CI feed and a
// pile of `.tmp/` probes stayed in the repo long after the rules meant to keep
// them out were written. The check is
//
//   git ls-files -z | git check-ignore -z -v --stdin --no-index
//
// which must report nothing outside ALLOWED below. Each ALLOWED entry is a path
// that must stay tracked although a rule ignores it, with the date it was
// recorded and why. An entry that no longer matches any tracked-ignored path
// fails the check too, so the list can only shrink deliberately.
//
// Exit codes: 0 clean · 1 offenders or stale allow-list entries · 2 git failed.

