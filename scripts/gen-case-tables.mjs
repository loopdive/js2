#!/usr/bin/env node
// (#40/#3773 standalone String case-mapping) Generate the Unicode simple,
// special, and context-property tables for `String.prototype.to{Upper,Lower}Case`
// used by the pure-Wasm native helpers under --target standalone/wasi.
//
// The data is DERIVED from the host Node.js Unicode tables (the same ICU the
// compiler's JS-host mode uses), so it tracks the Unicode version Node ships.
// Output is a committed TS module — CI does not regenerate; run this script
// manually to refresh after a Node major bump and commit the diff.
//
// Encoding:
//  - SIMPLE runs: a flat i32 array of [start, count, stride, delta] tuples,
//    sorted by `start`. Each tuple covers `count` code points beginning at
//    `start`, spaced `stride` apart (1 = contiguous, 2 = every-other — the
//    common Latin-Extended alternating even/odd case pairs), each mapping to
//    `cp + delta`. Binary-searchable by `start`.
//  - SPECIAL (1:N) entries: a flat i32 array of [cp, outLen, c0, c1, c2] (c2 = 0
//    when outLen < 3). These are the §SpecialCasing.txt unconditional full
//    mappings (e.g. U+00DF ß → "SS", U+0130 İ → "i̇"). All inputs + outputs are
//    BMP and outLen ≤ 3 (asserted below).
//  - PROPERTY ranges: flat [start,end] tuples for the Unicode `Cased` and
//    `Case_Ignorable` binary properties. `Final_Sigma` is the only
//    locale-insensitive conditional SpecialCasing rule and needs both.
//
// Usage: node scripts/gen-case-tables.mjs  (writes src/codegen/case-tables.ts)

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "src", "codegen", "case-tables.ts");

function simplePairs(which) {
  const pairs = [];
  for (let cp = 0; cp <= 0xffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue; // lone surrogates
    const s = String.fromCharCode(cp);
    const m = which === "upper" ? s.toUpperCase() : s.toLowerCase();
    if ([...m].length === 1) {
      const mc = m.codePointAt(0);
      if (mc !== cp) pairs.push([cp, mc - cp]);
    }
  }
  return pairs;
}

// Stride-aware run-length encoding. Greedily prefer the longer of a contiguous
// (stride 1) or alternating (stride 2) run starting at each unencoded cp.
function encodeRuns(pairs) {
  const delta = new Map(pairs);
  const used = new Set();
  const runs = [];
  for (const [cp, d] of pairs) {
    if (used.has(cp)) continue;
    let n1 = 1;
    while (delta.get(cp + n1) === d && !used.has(cp + n1)) n1++;
    let n2 = 1;
    while (delta.get(cp + 2 * n2) === d && !used.has(cp + 2 * n2)) n2++;
    if (n1 >= n2) {
      for (let k = 0; k < n1; k++) used.add(cp + k);
      runs.push([cp, n1, 1, d]);
    } else {
      for (let k = 0; k < n2; k++) used.add(cp + 2 * k);
      runs.push([cp, n2, 2, d]);
    }
  }
  runs.sort((a, b) => a[0] - b[0]);
  return runs;
}

function specialEntries(which) {
  const out = [];
  for (let cp = 0; cp <= 0xffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCharCode(cp);
    const m = which === "upper" ? s.toUpperCase() : s.toLowerCase();
    const cps = [...m].map((c) => c.codePointAt(0));
    if (cps.length > 1) {
      if (cps.length > 3) throw new Error(`special ${which} ${cp} outLen ${cps.length} > 3`);
      if (cp > 0xffff || cps.some((c) => c > 0xffff)) throw new Error(`astral special ${which} ${cp}`);
      out.push([cp, cps.length, cps[0], cps[1], cps[2] ?? 0]);
    }
  }
  out.sort((a, b) => a[0] - b[0]);
  return out;
}

function propertyRanges(property) {
  const re = new RegExp(`\\p{${property}}`, "u");
  const ranges = [];
  let start = -1;
  let previous = -1;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (re.test(String.fromCodePoint(cp))) {
      if (start < 0) start = cp;
      previous = cp;
    } else if (start >= 0) {
      ranges.push([start, previous]);
      start = -1;
    }
  }
  if (start >= 0) ranges.push([start, previous]);
  return ranges;
}

const upperRuns = encodeRuns(simplePairs("upper")).flat();
const lowerRuns = encodeRuns(simplePairs("lower")).flat();
const upperSpecial = specialEntries("upper").flat();
const lowerSpecial = specialEntries("lower").flat();
const casedRanges = propertyRanges("Cased").flat();
const caseIgnorableRanges = propertyRanges("Case_Ignorable").flat();

const banner =
  "// GENERATED by scripts/gen-case-tables.mjs — DO NOT EDIT BY HAND.\n" +
  "// Unicode simple + special case-mapping tables for the pure-Wasm\n" +
  "// String.prototype.to{Upper,Lower}Case helpers (#40, standalone/wasi).\n" +
  `// Derived from Node ${process.version} Unicode/ICU tables. Re-run the\n` +
  "// generator and commit after a Node major bump.\n\n";

const fmt = (name, arr, stride) => {
  // Pretty-print `stride` numbers per line for readability.
  const lines = [];
  for (let i = 0; i < arr.length; i += stride) {
    lines.push("  " + arr.slice(i, i + stride).join(", ") + ",");
  }
  return `export const ${name}: readonly number[] = [\n${lines.join("\n")}\n];\n`;
};

const body =
  banner +
  "// [start, count, stride, delta] tuples, sorted by start.\n" +
  fmt("UPPER_CASE_RUNS", upperRuns, 4) +
  "\n" +
  fmt("LOWER_CASE_RUNS", lowerRuns, 4) +
  "\n// [cp, outLen, c0, c1, c2] tuples (c2 = 0 when outLen < 3), sorted by cp.\n" +
  fmt("UPPER_CASE_SPECIAL", upperSpecial, 5) +
  "\n" +
  fmt("LOWER_CASE_SPECIAL", lowerSpecial, 5) +
  "\n// [start, end] inclusive Unicode binary-property ranges.\n" +
  fmt("CASED_RANGES", casedRanges, 2) +
  "\n" +
  fmt("CASE_IGNORABLE_RANGES", caseIgnorableRanges, 2);

writeFileSync(outPath, body);
console.log(
  `Wrote ${outPath}: upperRuns=${upperRuns.length / 4} lowerRuns=${lowerRuns.length / 4} ` +
    `upperSpecial=${upperSpecial.length / 5} lowerSpecial=${lowerSpecial.length / 5} ` +
    `casedRanges=${casedRanges.length / 2} caseIgnorableRanges=${caseIgnorableRanges.length / 2}`,
);
