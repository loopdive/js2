/**
 * Generate the finite Unicode properties of strings used by ECMAScript `v`
 * RegExp mode from the authoritative Unicode 17 UTS #51 data files.
 *
 * The emitted module is committed so compiler execution never fetches data.
 * Regeneration deliberately rejects a newer Unicode version: moving the
 * compiler's Unicode contract must be an explicit, reviewed version change.
 */
import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "17.0";
const SOURCES = [
  {
    name: "emoji-sequences.txt",
    url: "https://www.unicode.org/Public/UCD/latest/emoji/emoji-sequences.txt",
  },
  {
    name: "emoji-zwj-sequences.txt",
    url: "https://www.unicode.org/Public/UCD/latest/emoji/emoji-zwj-sequences.txt",
  },
];
const PROPERTY_NAMES = [
  "Basic_Emoji",
  "Emoji_Keycap_Sequence",
  "RGI_Emoji_Flag_Sequence",
  "RGI_Emoji_Tag_Sequence",
  "RGI_Emoji_Modifier_Sequence",
  "RGI_Emoji_ZWJ_Sequence",
];

function parseCodePoints(field) {
  const tokens = field.trim().split(/\s+/);
  if (tokens.length === 1 && tokens[0].includes("..")) {
    const [loText, hiText] = tokens[0].split("..");
    const lo = Number.parseInt(loText, 16);
    const hi = Number.parseInt(hiText, 16);
    return Array.from({ length: hi - lo + 1 }, (_, index) => [lo + index]);
  }
  return [tokens.map((token) => Number.parseInt(token, 16))];
}

function parseProperties(text) {
  const properties = new Map(PROPERTY_NAMES.map((name) => [name, new Map()]));
  for (const line of text.split(/\r?\n/)) {
    const data = line.split("#", 1)[0].trim();
    if (data === "") continue;
    const [codePointField, propertyField] = data.split(";").map((part) => part.trim());
    const property = properties.get(propertyField);
    if (property === undefined) continue;
    for (const sequence of parseCodePoints(codePointField)) {
      property.set(sequence.join("."), sequence);
    }
  }
  return properties;
}

function encode(properties) {
  return Object.fromEntries(
    PROPERTY_NAMES.map((name) => {
      const sequences = [...properties.get(name).values()].sort((left, right) => {
        for (let index = 0; index < Math.min(left.length, right.length); index++) {
          if (left[index] !== right[index]) return left[index] - right[index];
        }
        return left.length - right.length;
      });
      return [name, sequences.map((sequence) => sequence.map((cp) => cp.toString(36)).join(".")).join(",")];
    }),
  );
}

async function main() {
  const sourceTexts = [];
  const sourceMetadata = [];
  for (const source of SOURCES) {
    const response = await fetch(source.url);
    if (!response.ok) throw new Error(`${source.url}: HTTP ${response.status}`);
    const text = await response.text();
    const version = text.match(/^# Version: ([0-9.]+)$/m)?.[1];
    if (version !== UNICODE_VERSION) {
      throw new Error(`${source.name}: expected Unicode ${UNICODE_VERSION}, got ${version ?? "no version header"}`);
    }
    sourceTexts.push(text);
    sourceMetadata.push({
      ...source,
      sha256: createHash("sha256").update(text).digest("hex"),
    });
  }

  const merged = new Map(PROPERTY_NAMES.map((name) => [name, new Map()]));
  for (const text of sourceTexts) {
    for (const [name, sequences] of parseProperties(text)) {
      const target = merged.get(name);
      for (const [key, sequence] of sequences) target.set(key, sequence);
    }
  }
  for (const name of PROPERTY_NAMES) {
    if (merged.get(name).size === 0) throw new Error(`no Unicode data found for ${name}`);
  }

  const encoded = encode(merged);
  const sourceComments = sourceMetadata.map((source) => ` * - ${source.url}\n *   sha256 ${source.sha256}`).join("\n");
  const entries = PROPERTY_NAMES.map((name) => `  ${name}: ${JSON.stringify(encoded[name])},`).join("\n");
  const output = `// Copyright (c) 2026 Loopdive GmbH. Licensed under Apache-2.0 WITH LLVM-exception.
/**
 * GENERATED by scripts/generate-regexp-string-properties.mjs.
 * Unicode ${UNICODE_VERSION} finite RegExp properties of strings (UTS #51).
${sourceComments}
 *
 * Encoding: comma-separated sequences; base-36 code points separated by ".".
 * Do not edit by hand.
 */
export const UNICODE_STRING_PROPERTY_VERSION = ${JSON.stringify(UNICODE_VERSION)};

export const UNICODE_STRING_PROPERTY_DATA = {
${entries}
} as const;
`;
  const outputPath = fileURLToPath(new URL("../src/codegen/regex/unicode-string-data.generated.ts", import.meta.url));
  await writeFile(outputPath, output);
  for (const name of PROPERTY_NAMES) {
    console.log(`${name}: ${merged.get(name).size} sequences, ${encoded[name].length} encoded bytes`);
  }
  console.log(`wrote ${outputPath}`);
}

await main();
